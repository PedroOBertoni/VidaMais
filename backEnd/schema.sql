begin;

create table if not exists public.medicamentos (
  id bigint generated by default as identity primary key,
  sync_id text not null unique,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nome text not null,
  laboratorio text not null default '',
  validade date not null,
  indicacao text not null default '',
  contraindicacoes text not null default '',
  posologia text not null default '',
  efeitos_adversos text not null default '',
  precaucoes text not null default '',
  observacoes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Completa instalações anteriores sem apagar linhas existentes.
alter table public.medicamentos add column if not exists sync_id text;
alter table public.medicamentos add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.medicamentos add column if not exists nome text;
alter table public.medicamentos add column if not exists laboratorio text not null default '';
alter table public.medicamentos add column if not exists validade date;
alter table public.medicamentos add column if not exists indicacao text not null default '';
alter table public.medicamentos add column if not exists contraindicacoes text not null default '';
alter table public.medicamentos add column if not exists posologia text not null default '';
alter table public.medicamentos add column if not exists efeitos_adversos text not null default '';
alter table public.medicamentos add column if not exists precaucoes text not null default '';
alter table public.medicamentos add column if not exists observacoes text not null default '';
alter table public.medicamentos add column if not exists created_at timestamptz not null default now();
alter table public.medicamentos add column if not exists updated_at timestamptz not null default now();
alter table public.medicamentos add column if not exists texto_ocr text not null default '';
alter table public.medicamentos add column if not exists leitura_em text not null default '';

-- Identificadores para registros legados sem sync_id; preserva as linhas e suas chaves.
update public.medicamentos
set sync_id = 'legacy-' || id::text
where sync_id is null or btrim(sync_id) = '';
create unique index if not exists medicamentos_sync_id_idx on public.medicamentos(sync_id);

alter table public.medicamentos enable row level security;

-- Permissões da API: a sessão anônima autenticada usa o papel authenticated.
-- RLS restringe quais linhas esse papel pode acessar.
revoke all on table public.medicamentos from anon, authenticated;
grant usage on schema public to authenticated;
grant select, insert, update, delete on table public.medicamentos to authenticated;
grant usage on sequence public.medicamentos_id_seq to authenticated;

create index if not exists medicamentos_user_id_idx on public.medicamentos(user_id);

-- NOT VALID preserva registros legados; inclusões e alterações já são validadas.
alter table public.medicamentos drop constraint if exists medicamentos_dados_validos;
alter table public.medicamentos add constraint medicamentos_dados_validos check (
  sync_id is not null and sync_id ~ '[^[:space:]]'
  and nome is not null and nome ~ '[^[:space:]]'
  and validade is not null and isfinite(validade)
) not valid;

alter table public.medicamentos drop constraint if exists medicamentos_sync_id_nao_vazio;
alter table public.medicamentos add constraint medicamentos_sync_id_nao_vazio
  check (sync_id is not null and sync_id ~ '[^[:space:]]') not valid;

-- Sessões anônimas são usuários autenticados: não aceitar user_id enviado de outro usuário.
alter table public.medicamentos drop constraint if exists medicamentos_user_id_obrigatorio;
alter table public.medicamentos add constraint medicamentos_user_id_obrigatorio
  check (user_id is not null) not valid;

-- Mantém a identificação estável e registra no servidor a última gravação.
create or replace function public.preparar_medicamento()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if TG_OP = 'INSERT' and new.user_id is null then
    new.user_id := auth.uid();
  end if;
  if TG_OP = 'INSERT' and new.user_id is distinct from auth.uid() then
    raise exception 'O registro deve pertencer à sessão autenticada.'
      using errcode = '42501';
  end if;
  if TG_OP = 'UPDATE' then
    if new.id is distinct from old.id
       or new.sync_id is distinct from old.sync_id
       or new.user_id is distinct from old.user_id then
      raise exception 'Os identificadores do medicamento não podem ser alterados.'
        using errcode = '23514';
    end if;
    new.created_at := old.created_at;
  end if;
  new.updated_at := clock_timestamp();
  return new;
end;
$$;

revoke all on function public.preparar_medicamento() from public;
drop trigger if exists preparar_medicamento on public.medicamentos;
create trigger preparar_medicamento
before insert or update on public.medicamentos
for each row execute function public.preparar_medicamento();

drop policy if exists "vida_public_select" on public.medicamentos;
drop policy if exists "vida_public_insert" on public.medicamentos;
drop policy if exists "vida_public_update" on public.medicamentos;
drop policy if exists "vida_public_delete" on public.medicamentos;
drop policy if exists "vida_user_select" on public.medicamentos;
drop policy if exists "vida_user_insert" on public.medicamentos;
drop policy if exists "vida_user_update" on public.medicamentos;
drop policy if exists "vida_user_delete" on public.medicamentos;

create policy "vida_user_select" on public.medicamentos
  for select to authenticated using (auth.uid() = user_id);
create policy "vida_user_insert" on public.medicamentos
  for insert to authenticated with check (auth.uid() = user_id);
create policy "vida_user_update" on public.medicamentos
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "vida_user_delete" on public.medicamentos
  for delete to authenticated using (auth.uid() = user_id);

commit;
